/**
 * Locator stability: how likely a locator chain a test uses is to break for a
 * reason unrelated to what the test checks — a restyle, a wrapper added around
 * an element, an item added to a list, a copy edit, other data.
 *
 * Judged from the chain's text alone, with a few named rules, so every client
 * of the locator index (the browser extension on a live page, the dashboard's
 * Locators page) reads the same verdict without anything being stored. CSS and
 * XPath selectors are read by a small tokenizer, not a selector engine: it only
 * needs to see classes, ids, attributes, pseudo-classes and combinators.
 */
import {
  LOCATING_METHODS,
  tryParseLocatorChain,
  type LocatorArg,
  type LocatorCall,
  type LocatorChain,
} from './locator-chain';
import { classifyCssStability, isAutoGenerated } from './locator-generation';

/** `stable`: nothing to say. `watch`: could break, worth a look. `brittle`: breaks on unrelated changes. */
export type LocatorStabilityLevel = 'stable' | 'watch' | 'brittle';

export type LocatorStabilityRuleId =
  | 'position'
  | 'css-class'
  | 'css-structure'
  | 'xpath'
  | 'generated-id'
  | 'style-attribute'
  | 'long-text'
  | 'data-text'
  | 'deep-chain';

export interface LocatorStabilityRule {
  id: LocatorStabilityRuleId;
  /** A few words for lists and cards: `position`, `CSS class`. */
  label: string;
  /** The highest level the rule gives a chain. */
  level: Exclude<LocatorStabilityLevel, 'stable'>;
  /** What the rule catches and why that breaks. */
  description: string;
}

